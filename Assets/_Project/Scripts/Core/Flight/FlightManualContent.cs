using System;
using System.Collections.Generic;
using SpaceSim.Physics;
using SpaceSim.Planets;
using SpaceSim.Units;

namespace SpaceSim.Flight
{
    /// <summary>
    /// Text of the in-game Flight Manual. Worked examples are computed live from the current planet's data,
    /// so they stay correct when the planet's mass, radius or atmosphere is changed.
    /// Uses IMGUI rich-text tags (&lt;b&gt;, &lt;i&gt;, &lt;color&gt;).
    /// </summary>
    public static class FlightManualContent
    {
        public readonly struct Section
        {
            public Section(string title, string body)
            {
                Title = title;
                Body = body;
            }

            public string Title { get; }
            public string Body { get; }
        }

        const string F = "<color=#9fd8ff><b>";
        const string EF = "</b></color>";
        const string Warn = "<color=#ffc36b><b>";
        const string EW = "</b></color>";

        static string N(double v, int d) => UnitFormatter.Number(v, d);
        static string Km(double m) => UnitFormatter.Number(m / 1000.0, 1) + " км";

        public static List<Section> Build(PlanetModel planet, double launchLatitudeDeg)
        {
            double mu = planet.GravitationalParameter;
            double R = planet.Radius;
            double g0 = mu / (R * R);
            double r200 = R + 200000.0, r400 = R + 400000.0;
            double vc200 = OrbitalMechanics.CircularVelocity(mu, r200);
            double vc400 = OrbitalMechanics.CircularVelocity(mu, r400);
            double ve0 = OrbitalMechanics.EscapeVelocity(mu, R);
            double ve400 = OrbitalMechanics.EscapeVelocity(mu, r400);
            double T400 = OrbitalMechanics.CircularPeriod(mu, r400);
            double g400 = mu / (r400 * r400);
            double lat = launchLatitudeDeg * Math.PI / 180.0;
            double vRot = planet.Rotation.AngularSpeed * R * Math.Cos(lat);
            double boundary = planet.SpaceBoundaryAltitude;
            double vUp100 = Math.Sqrt(2.0 * mu * (1.0 / R - 1.0 / (R + boundary)));
            var atm = planet.Atmosphere;
            bool hasAir = atm.ReferenceDensity > 0.0;
            double rho0 = atm.ReferenceDensity;
            double H = hasAir && atm is ExponentialAtmosphere ea ? ea.ScaleHeight : double.NaN;
            double vt = hasAir ? AtmosphericDrag.TerminalVelocity(500.0, g0, rho0, 1.05, Math.PI) : double.NaN;

            var s = new List<Section>();

            s.Add(new Section("1. Единицы и обозначения",
                "Все расчёты симулятора ведутся в системе СИ; интерфейс только округляет числа.\n\n" +
                "• расстояние — метры (м); время — секунды (с); масса — килограммы (кг)\n" +
                "• скорость — м/с; ускорение — м/с²; сила — ньютоны (Н = кг·м/с²)\n" +
                "• энергия — джоули (Дж); удельная энергия — Дж/кг = м²/с²\n" +
                "• давление — паскали (Па); плотность — кг/м³; температура — кельвины (К)\n\n" +
                "<b>Обозначения</b>\n" +
                "G — гравитационная постоянная = 6.67430·10⁻¹¹ м³/(кг·с²)\n" +
                "M — масса планеты; μ = G·M — гравитационный параметр [м³/с²]\n" +
                "R — средний (опорный) радиус планеты; r — расстояние от ЦЕНТРА планеты до аппарата\n" +
                "h = r − R — высота над опорной сферой; v — модуль скорости; v_r — её радиальная (вертикальная) часть\n\n" +
                "Для текущей планеты: μ = " + UnitFormatter.Scientific(mu, 6) + " м³/с², R = " + N(R, 0) + " м, g(R) = " + N(g0, 3) + " м/с².\n\n" +
                Warn + "Частая ошибка:" + EW + " смешивать км и м в одной формуле. Переводите всё в метры до вычислений."));

            s.Add(new Section("2. Высота, радиус орбиты, расстояние от центра",
                "Формулы гравитации и орбит работают с расстоянием от центра " + F + "r" + EF + ", а не с высотой.\n\n" +
                F + "r = R + h" + EF + "\n\n" +
                "Приборы показывают три величины:\n" +
                "• <b>Высота над поверхностью</b> — до реального рельефа под аппаратом (горы, океан). Нужна для посадки.\n" +
                "• <b>Высота над R</b> — над опорной сферой радиуса R. Так задаются орбиты и граница космоса.\n" +
                "• <b>От центра (r)</b> — то, что подставляется в формулы.\n\n" +
                "<b>Пример.</b> Орбита на высоте 400 км: r = " + N(R, 0) + " + 400 000 = " + N(r400, 0) + " м.\n\n" +
                Warn + "Частая ошибка:" + EW + " подставить h = 400 000 м вместо r в √(μ/r). Получится "
                + N(Math.Sqrt(mu / 400000.0), 0) + " м/с вместо " + N(vc400, 0) + " м/с."));

            s.Add(new Section("3. Скорость и ускорение",
                "<b>Скорость</b> — как быстро и куда меняется положение (вектор, м/с). <b>Ускорение</b> — как быстро меняется сама скорость (вектор, м/с²).\n" +
                "Гравитация задаёт ускорение, а не скорость: на орбите тело всё время ускоряется к центру, но модуль скорости почти не меняется — меняется её направление.\n\n" +
                "<b>Три скорости на приборах</b>\n" +
                "• инерциальная — относительно звёзд; именно она входит в орбитальные формулы;\n" +
                "• относительно поверхности — v − ω×r, то, что видит наблюдатель на земле;\n" +
                "• относительно воздуха — для сопротивления (при отсутствии ветра совпадает с предыдущей).\n\n" +
                "Покоящийся на стартовой площадке аппарат (широта " + N(launchLatitudeDeg, 2) + "°) уже движется инерциально на восток со скоростью " +
                F + "ω·R·cos φ ≈ " + N(vRot, 1) + " м/с" + EF + ". Старт на восток экономит эту скорость, на запад — добавляет её к требуемой.\n\n" +
                "<b>Перегрузка</b> (акселерометр) — ускорение без учёта гравитации. На площадке ≈ 1 g₀, в свободном полёте (в том числе на орбите) = 0, хотя g(r) ≠ 0.\n\n" +
                Warn + "Частая ошибка:" + EW + " «на орбите нет гравитации». На 400 км g = " + N(g400, 2) + " м/с² — " + N(100.0 * g400 / g0, 0) + "% от поверхностной. Невесомость — это свободное падение."));

            s.Add(new Section("4. Закон всемирного тяготения",
                F + "F = G·M·m / r²" + EF + "     " + F + "g(r) = μ / r²" + EF + "     " + F + "a⃗ = −μ·r⃗ / |r⃗|³" + EF + "\n\n" +
                "r⃗ направлен от центра планеты к аппарату, знак «−» означает притяжение к центру. Масса аппарата m в ускорение не входит — все тела падают одинаково.\n\n" +
                "<b>Когда применимо:</b> сферически-симметричная планета, точка вне её. Не учитываются сплюснутость (J2), неоднородности масс, приливы, другие тела.\n\n" +
                "<b>Пример.</b> g(R) = " + UnitFormatter.Scientific(mu, 4) + " / " + N(R, 0) + "² = " + N(g0, 3) + " м/с²;  g(R+400 км) = " + N(g400, 3) + " м/с².\n" +
                "(Привычные 9.81 м/с² на Земле включают центробежный эффект вращения и сплюснутость; чистая гравитация на среднем радиусе ≈ 9.82.)\n\n" +
                Warn + "Частая ошибка:" + EW + " считать g постоянным на любой высоте. Используйте g(r) = μ/r²."));

            s.Add(new Section("5. Почему орбите нужна горизонтальная скорость",
                "Орбита — это непрерывное падение, при котором аппарат «промахивается» мимо планеты. За время падения он успевает сместиться вбок настолько, что поверхность изгибается вниз вместе с ним.\n\n" +
                "• Вертикальная скорость только поднимает аппарат: без горизонтальной составляющей он упадёт обратно по той же линии.\n" +
                "• Чтобы подняться на " + Km(boundary) + " вертикально (без атмосферы), нужно около " + F + N(vUp100, 0) + " м/с" + EF + " — из ε = const: v² = 2μ(1/R − 1/(R+h)).\n" +
                "• Чтобы на той же высоте не упасть, нужно около " + F + N(OrbitalMechanics.CircularVelocity(mu, R + boundary), 0) + " м/с" + EF + " горизонтально.\n\n" +
                "Радиальная скорость v_r на приборах показывает, сближаетесь ли вы с центром (v_r < 0) или удаляетесь (v_r > 0). На круговой орбите v_r ≈ 0.\n\n" +
                Warn + "Частая ошибка:" + EW + " набрать высоту и ждать, что аппарат «останется в космосе». Попробуйте в инструменте начальных условий (I): h = 150 000, все скорости 0 — и посмотрите, что произойдёт."));

            s.Add(new Section("6. Круговая орбитальная скорость",
                F + "v_круг = √(μ / r)" + EF + "\n\n" +
                "Получается из равенства центростремительного ускорения v²/r и гравитационного μ/r².\n\n" +
                "<b>Пример.</b> h = 200 км: r = " + N(r200, 0) + " м, v = √(" + UnitFormatter.Scientific(mu, 4) + " / " + N(r200, 0) + ") = " + F + N(vc200, 1) + " м/с" + EF + ".\n" +
                "h = 400 км: v = " + N(vc400, 1) + " м/с — выше орбита, ниже скорость.\n\n" +
                "<b>Предположения:</b> двухтельная задача, без атмосферы; скорость инерциальная и направлена строго горизонтально.\n\n" +
                Warn + "Частые ошибки:" + EW + " (1) подставить высоту вместо r; (2) задать скорость «относительно поверхности» и забыть, что инерциальная скорость будет больше на ω·R·cos φ при движении на восток; (3) добавить вертикальную составляющую — орбита станет эллиптической."));

            s.Add(new Section("7. Вторая космическая (скорость убегания)",
                F + "v_уход = √(2μ / r) = √2 · v_круг" + EF + "\n\n" +
                "Минимальная скорость, при которой ε ≥ 0 и аппарат не вернётся (в идеальной модели — без атмосферы, без вращения, без других тел). Направление не важно, если траектория не пересекает планету.\n\n" +
                "<b>Пример.</b> С поверхности: " + N(ve0, 0) + " м/с; с высоты 400 км: " + N(ve400, 0) + " м/с.\n\n" +
                Warn + "Частая ошибка:" + EW + " считать её скоростью, которую нужно набрать у поверхности в реальной атмосфере: сопротивление и потери на гравитацию требуют больше."));

            s.Add(new Section("8. Удельная орбитальная энергия",
                F + "ε = v²/2 − μ/r" + EF + "    [Дж/кг]\n\n" +
                "Сумма кинетической и потенциальной энергии на килограмм. Без сопротивления и двигателей ε постоянна — это хороший контроль точности симуляции.\n" +
                "• ε < 0 — движение связанное (эллипс), аппарат не может уйти бесконечно далеко;\n" +
                "• ε = 0 — параболическая граница;\n" +
                "• ε > 0 — гипербола, уход от планеты.\n" +
                "Для круговой орбиты ε = −μ/(2r); на 400 км: " + N(-mu / (2.0 * r400), 0) + " Дж/кг.\n\n" +
                Warn + "Важно:" + EW + " ε < 0 НЕ означает устойчивую орбиту. Тело, неподвижно зависшее на 100 км, имеет ε = " + N(-mu / (R + boundary), 0) +
                " Дж/кг < 0 — и падает. Нужно ещё, чтобы перицентр r_p = h²/(μ(1+e)) был выше поверхности и плотной атмосферы."));

            s.Add(new Section("9. Период круговой орбиты",
                F + "T = 2π · √(r³ / μ)" + EF + "\n\n" +
                "Для эллипса вместо r подставляется большая полуось a = −μ/(2ε) (третий закон Кеплера).\n\n" +
                "<b>Пример.</b> h = 400 км: T = 2π·√(" + N(r400, 0) + "³ / " + UnitFormatter.Scientific(mu, 4) + ") = " + F + N(T400, 0) + " с ≈ " + N(T400 / 60.0, 1) + " мин" + EF + ".\n\n" +
                Warn + "Частая ошибка:" + EW + " забыть возвести r в куб или использовать километры с μ в м³/с²."));

            string airText = hasAir
                ? "Модель плотности: " + F + "ρ(h) = ρ₀ · e^(−h/H)" + EF + (double.IsNaN(H) ? " (сейчас — табличная модель)" : ", ρ₀ = " + N(rho0, 3) + " кг/м³, H = " + N(H, 0) + " м") + ".\n" +
                  "ρ(0) = " + UnitFormatter.Density(atm.Density(0)) + "; ρ(10 км) = " + UnitFormatter.Density(atm.Density(10000)) +
                  "; ρ(50 км) = " + UnitFormatter.Density(atm.Density(50000)) + "; ρ(100 км) = " + UnitFormatter.Density(atm.Density(100000)) +
                  "; ρ(200 км) = " + UnitFormatter.Density(atm.Density(200000)) + ".\n" +
                  "Плотность убывает плавно и не обращается в ноль ни на какой высоте.\n\n" +
                  "<b>Сопротивление</b>: " + F + "F = ½ · ρ · v_rel² · Cd · A" + EF + ", направлено против скорости относительно воздуха.\n" +
                  "Скоростной напор q = ½ρv² [Па] показан на приборах.\n" +
                  "Предельная скорость падения: " + F + "v_t = √(2mg / (ρ·Cd·A))" + EF + ". Для тестового зонда (m = 500 кг, Cd = 1.05, A = π м²) у поверхности: ≈ " + N(vt, 0) + " м/с.\n\n" +
                  "<b>Не учитывается:</b> подъёмная сила, зависимость Cd от числа Маха, нагрев, ветер, суточные изменения атмосферы."
                : "У этой планеты нет атмосферы: сопротивления нет, орбиты возможны на любой высоте выше рельефа.";
            s.Add(new Section("10. Атмосфера и сопротивление", airText + "\n\n" +
                Warn + "Частая ошибка:" + EW + " брать в формулу сопротивления инерциальную скорость. Воздух вращается вместе с планетой: на площадке инерциальная скорость ≈ " +
                N(vRot, 0) + " м/с, а сопротивления нет."));

            s.Add(new Section("11. Почему 100 км — ещё не орбита",
                "Высота " + Km(boundary) + " — <b>условная</b> граница космоса (линия Кармана). Это соглашение, а не физический край: атмосфера продолжается выше, просто становится очень разреженной.\n\n" +
                "Достичь высоты и выйти на орбиту — разные задачи:\n" +
                "• для высоты нужна энергия на подъём (≈ " + N(vUp100, 0) + " м/с вертикально);\n" +
                "• для орбиты нужна горизонтальная скорость ≈ " + N(OrbitalMechanics.CircularVelocity(mu, R + boundary), 0) + " м/с — в несколько раз больше;\n" +
                "• на высоте ~100–140 км сопротивление ещё заметно: орбита с таким перицентром быстро снижается. Симулятор называет орбиту устойчивой, только если ε < 0 и перицентр выше порога (по умолчанию 140 км).\n\n" +
                "Поэтому интерфейс сообщает о пересечении границы, но фазу «Орбитальный полёт» показывает только по орбитальным критериям."));

            s.Add(new Section("12. Как пользоваться приборами при планировании",
                "1. Выберите целевую высоту h и посчитайте r = R + h.\n" +
                "2. Посчитайте v_круг = √(μ/r) и период T.\n" +
                "3. Учтите вращение: если задаёте скорость относительно поверхности на восток, вычтите ω·R·cos φ (" + N(vRot, 1) + " м/с на площадке).\n" +
                "4. Откройте начальные условия (I), задайте h и горизонтальную скорость, вертикальную = 0. Примените.\n" +
                "5. Проверьте: ε должна быть ≈ −μ/(2r), v_r должна колебаться около нуля, высота — оставаться почти постоянной.\n" +
                "6. Сравните со значениями анализа орбиты (O). Расхождение — повод найти ошибку в расчёте.\n" +
                "7. Попробуйте ускорение времени (.) — физический шаг не меняется, результаты не зависят от FPS.\n\n" +
                "<b>Эксперименты:</b> скорость на 5% меньше круговой (эллипс с перицентром ниже), на 5% больше; запуск с v = v_уход; орбита на 110 км со включённым сопротивлением."));

            s.Add(new Section("13. Двигатели и топливо (будущая фаза)",
                "В этой фазе двигателей нет — аппарат движется только под действием гравитации и сопротивления. Расход топлива не моделируется и не изображается.\n\n" +
                "Будущая модель будет основана на:\n" +
                "• тяге F [Н] и удельном импульсе I_sp [с];\n" +
                "• массовом расходе " + F + "ṁ = F / (I_sp · g₀)" + EF + " [кг/с], где g₀ = 9.80665 м/с² — единица, а не местная гравитация;\n" +
                "• уравнении Циолковского " + F + "Δv = I_sp · g₀ · ln(m₀ / m_к)" + EF + ";\n" +
                "• массе аппарата, меняющейся во времени: m(t) = m₀ − ṁ·t.\n" +
                "Подробности — в PHYSICS.md."));

            return s;
        }
    }
}
